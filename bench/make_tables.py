"""
bench.make_tables — emit paper-ready tables with REAL numbers.
"""

from __future__ import annotations

import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from . import config, store  # noqa: E402
from .metrics import compute_all  # noqa: E402


def _pct(v, lo=None, hi=None) -> str:
    if v is None:
        return "n/a"
    s = f"{v * 100:.1f}"
    if lo is not None and hi is not None:
        s += f" [{lo * 100:.1f}–{hi * 100:.1f}]"
    return s


def build() -> str:
    rep = compute_all()
    L = []
    A = L.append

    A("# TrialBridge — paper tables (auto-generated)")
    A("")
    A("Generated by `python -m bench.make_tables`. Every number traces to files in")
    A("`bench_out/`. Do not hand-edit; regenerate.")
    A("")

    patients = store.read_jsonl(config.PATIENTS_FILE)
    criteria = store.read_jsonl(config.CRITERIA_FILE)
    anns = store.read_jsonl(config.ANNOTATIONS_FILE)
    a2 = store.read_jsonl(config.ANNOTATIONS_A2_FILE)

    by_cohort = {}
    for c in criteria:
        d = by_cohort.setdefault(c["cohort"], {"criteria": 0, "trials": set()})
        d["criteria"] += 1
        d["trials"].add(c["nct_id"])
    pat_by_cohort = {}
    for p in patients:
        pat_by_cohort[p["cohort"]] = pat_by_cohort.get(p["cohort"], 0) + 1
    ann_by_cohort = {}
    crit_cohort = {c["criterion_id"]: c["cohort"] for c in criteria}
    for a in anns:
        ch = crit_cohort.get(a["criterion_id"], "?")
        ann_by_cohort[ch] = ann_by_cohort.get(ch, 0) + 1

    A("## Table 1. Dataset composition")
    A("")
    A("| Cohort | Trials | Atomic criteria | Patients | Annotated pairs |")
    A("|---|---|---|---|---|")
    for ch in sorted(set(list(by_cohort) + list(pat_by_cohort))):
        d = by_cohort.get(ch, {"criteria": 0, "trials": set()})
        A(f"| {ch} | {len(d['trials'])} | {d['criteria']} | "
          f"{pat_by_cohort.get(ch, 0)} | {ann_by_cohort.get(ch, 0)} |")
    A(f"| **total** | {len({c['nct_id'] for c in criteria})} | {len(criteria)} | "
      f"{len(patients)} | {len(anns)} |")
    A("")

    dist = store.label_distribution(anns)
    if dist:
        A("Label distribution: " +
          ", ".join(f"{k} {v['count']} ({v['fraction']:.1%})" for k, v in sorted(dist.items())))
        A("")
        if dist.get("INELIGIBLE", {}).get("fraction", 0) < config.BALANCE_FLOOR["INELIGIBLE"]:
            A("> **Warning:** INELIGIBLE is under the pre-set floor. Accuracy on this")
            A("> benchmark cannot yet distinguish a real model from a stub that never")
            A("> predicts INELIGIBLE. Author more patients that trigger it before claiming.")
            A("")

    A("## Table 2. Per-criterion accuracy by criterion type")
    A("")
    A("Selective (non-abstained) accuracy, 95% CI bootstrapped clustered by patient.")
    A("")
    runs = rep["runs"]
    clean_runs = {k: v for k, v in runs.items() if k.endswith("::clean")}
    if not clean_runs:
        A("_No clean-arm runs yet — `python -m bench.run_eval`._")
    for key, e in sorted(clean_runs.items()):
        A("")
        A(f"**{key}** (n={e['n_pairs']} pairs, {e['n_patients']} patients)")
        A("")
        A("| Criterion type | n | Accuracy [95% CI] |")
        A("|---|---|---|")
        for ct, v in sorted(e["by_ctype"].items()):
            flag = " *(underpowered)*" if v.get("underpowered") else ""
            A(f"| {ct} | {v['n']} | {_pct(v['point'], v['lo'], v['hi'])}{flag} |")
        sa = e["selective_accuracy"]
        A(f"| **overall** | {e['n_pairs']} | **{_pct(sa['point'], sa['lo'], sa['hi'])}** |")
        A("")
        stub = e.get("always_eligible_stub")
        if stub is not None:
            A(f"Always-ELIGIBLE stub baseline: {stub * 100:.1f}%. "
              "Any reported accuracy must clear this to mean anything.")

    A("")
    A("## Table 3. Ablation across backends (clean arm, identical inputs)")
    A("")
    A("| Backend | n pairs | Selective acc. [95% CI] | Coverage | Molecular acc. | Span support |")
    A("|---|---|---|---|---|---|")
    for key, e in sorted(clean_runs.items()):
        sa, cv, ss = e["selective_accuracy"], e["coverage"], e["span_support"]
        mol = e["by_ctype"].get("molecular")
        molx = _pct(mol["point"], mol["lo"], mol["hi"]) if mol else "n/a"
        A(f"| {key.replace('::clean', '')} | {e['n_pairs']} | "
          f"{_pct(sa['point'], sa['lo'], sa['hi'])} | {_pct(cv['point'])} | {molx} | "
          f"{_pct(ss['point'])} |")
    A("")

    A("## Table 4. Equity slice — clean vs community-style, same patients (PRIMARY)")
    A("")
    if not rep["paired_equity"]:
        A("_No paired runs yet — run both arms: `python -m bench.run_eval`._")
    for tag, e in sorted(rep["paired_equity"].items()):
        d = e["delta"]
        A(f"**{tag}** (n={e['n_paired']} paired pairs)")
        A("")
        A("| Criterion type | Clean | Degraded | Δ (clean−deg) [95% CI] |")
        A("|---|---|---|---|")
        for ct, v in sorted(e["by_ctype"].items()):
            dd = v["delta"]
            A(f"| {ct} | {_pct(v['clean'])} | {_pct(v['degraded'])} | "
              f"{_pct(dd['point'], dd['lo'], dd['hi'])} |")
        A(f"| **overall** | **{_pct(e['clean_accuracy'])}** | "
          f"**{_pct(e['degraded_accuracy'])}** | "
          f"**{_pct(d['point'], d['lo'], d['hi'])}** |")
        A("")
        A(f"Abstention: clean {e['clean_abstention']:.1%} → degraded {e['degraded_abstention']:.1%}.")
        if d["lo"] is not None and d["lo"] <= 0 <= d["hi"]:
            A("")
            A("> The CI includes zero. State plainly that a robustness difference was")
            A("> **not** demonstrated; do not describe this as robustness 'holding'.")
        A("")

    if rep["extraction"]:
        A("## Extraction fidelity (Stage 1)")
        A("")
        A("| Run | Patients | Precision | Recall | Correct-null rate |")
        A("|---|---|---|---|---|")
        for key, e in sorted(rep["extraction"].items()):
            A(f"| {key} | {e['n_patients']} | {_pct(e['precision'])} | "
              f"{_pct(e['recall'])} | {_pct(e['correct_null_rate'])} |")
        A("")
        A("Correct-null rate = fraction of genuinely absent fields the model left null")
        A("instead of inventing. Low values mean hallucinated structure.")
        A("")

    iaa_path = os.path.join(config.RESULTS_DIR, "iaa.json")
    A("## Inter-annotator agreement")
    A("")
    if os.path.exists(iaa_path):
        iaa = store.read_json(iaa_path)
        A(f"Overlapping pairs: {iaa['n_shared']}; raw agreement "
          f"{iaa['raw_agreement']:.3f}; Cohen's κ {iaa['cohens_kappa']:.3f}")
        A("")
        A("| Criterion type | n | κ |")
        A("|---|---|---|")
        for r in iaa.get("by_ctype", []):
            low = " *(low n)*" if r["n"] < 20 else ""
            A(f"| {r['ctype']} | {r['n']} | {r['kappa']:.3f}{low} |")
    else:
        A("_Not computed. A second annotator is required:_")
        A("`python -m bench.annotate --second` then `python -m bench.annotate --iaa`")
        A("")
        A("> Both manuscripts promise annotator independence. Without a second")
        A("> annotator this is the weakest point a reviewer will find.")
    A("")
    A(f"A2 annotations on disk: {len(a2)}")
    A("")
    A("---")
    A("")
    A("### Reporting reminders")
    A("- Report CIs for every stratified estimate; do not interpret overlapping intervals.")
    A("- Degraded-arm gold policy: `" + config.DEGRADED_GOLD_POLICY + "` (pre-register it).")
    A("- Degradation transforms: " + ", ".join(config.DEGRADE_TRANSFORMS))
    A("- The cloud backend is evaluation-only and must never see real patient data.")
    return "\n".join(L) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Emit paper-ready tables.")
    ap.add_argument("--print", action="store_true")
    args = ap.parse_args(argv)
    config.ensure_dirs()
    md = build()
    path = os.path.join(config.RESULTS_DIR, "paper_tables.md")
    store.write_text(path, md)
    if args.print:
        print(md)
    print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
